#!/usr/bin/env python3
"""The bodies M-Film knows, as a header the darkroom includes: the one place a
body's scale and its sensor's colours are named.

    python3 gencams.py ../fos_cams.h [--cameras ../../cameras.txt]

The names come from ml-dev/cameras.txt, which is where the fork's cameras are
listed, each row's own name and the aliases Canon writes for it. The values are
the ones the fork was built with, per body:

  white  the raw value of a full pixel, LibRaw's maximum for the body; the EOS
         M's was measured. It is the scale: what a frame's samples are divided
         by (fos_dev.c, WHITE_LEVEL).
  xyz    the sensor's colours, XYZ -> camera, from LibRaw's colordata.cpp, the
         Adobe matrices, per body the fork is built for (fos_dev.c, XYZ_CAM).

A camera build takes its own from the chain the header writes, as it did from
the chain in fos_dev.c. A computer build is built for no camera at all, so it
falls past every arm to the EOS M's number, which for a 6D is 13.9 per cent out.
The header writes the table below as well, and the darkroom looks the frame's own
name up in it (#132). A name that is not there leaves the build's own numbers, so
an unknown body develops as it did and a camera build does not move.

The header is written into the tree and committed, as fos_font.c is, because the
camera's build cannot run this. sim/tabletest.sh fails when the file is not what
this says.
"""
import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

# per body: its white, and the key of the matrix it uses. The keys are
# ml-dev/cameras.txt's own.
BODIES = {
    '6D':    (15490, '6D'),
    '70D':   (15303, '6D'),      # one sensor with the 6D
    '5D3':   (15488, '5D3'),
    '5D2':   (15600, '5D2'),
    '7D':    (13584, '7D'),
    '50D':   (15763, '50D'),
    '60D':   (12279, '60D'),
    '500D':  (13433, '500D'),
    '550D':  (15831, '550D'),
    '600D':  (13584, '600D'),
    '1100D': (13584, '1100D'),
    '1300D': (13584, '1300D'),
    '100D':  (13583, 'EOSM'),    # one sensor with the EOS M, 650D and 700D
    '650D':  (13645, 'EOSM'),
    '700D':  (15360, 'EOSM'),
    'EOSM':  (13600, 'EOSM'),
}

# the sensor's colours, in ten-thousandths, from LibRaw's colordata.cpp, once
# for each group of bodies that shares one
MATRICES = {
    '6D':    (7034, -804, -1014, -4420, 12564, 2058, -851, 1994, 5758),
    '5D3':   (6722, -635, -963, -4287, 12460, 2028, -908, 2162, 5668),
    '5D2':   (4716, 603, -830, -7798, 15474, 2480, -1496, 1937, 6651),
    '7D':    (6844, -996, -856, -3876, 11761, 2396, -593, 1772, 6198),
    '50D':   (4920, 616, -593, -6493, 13964, 2784, -1774, 3178, 7005),
    '60D':   (6719, -994, -925, -4408, 12426, 2211, -887, 2129, 6051),
    '500D':  (4763, 712, -646, -6821, 14399, 2640, -1921, 3276, 6561),
    '550D':  (6941, -1164, -857, -3825, 11597, 2534, -416, 1540, 6039),
    '600D':  (6461, -907, -882, -4300, 12184, 2378, -819, 1944, 5931),
    '1100D': (6444, -904, -893, -4563, 12308, 2535, -903, 2016, 6728),
    '1300D': (6939, -1016, -866, -4428, 12473, 2177, -1175, 2178, 6162),
    'EOSM':  (6602, -841, -939, -4472, 12458, 2247, -975, 2039, 6148),
}

# the body its build falls to when no camera is configured: no CONFIG_ of its
# own, and the one a name we do not know is left with
FALLBACK = 'EOSM'

BANNER = """/* generated by tools/gencams.py from ml-dev/cameras.txt and the bodies it knows -
 * do not edit. The one place a body's own scale and its sensor's colours are named: a
 * camera build takes its own from the chain below, and the computer build, which is
 * built for no camera at all, looks the frame's own name up in the table. */

#ifndef FOS_CAMS_H
#define FOS_CAMS_H

/* the sensor's colours, XYZ -> camera, from LibRaw's colordata.cpp (the Adobe
 * matrices), once for each group of bodies that shares one */
"""


def names_from(cameras):
    """Every name Canon may have written for a body, from the fork's own list."""
    out = []
    for line in Path(cameras).read_text().splitlines():
        if line.startswith('#') or not line.strip():
            continue
        fields = line.split('|')[0].strip().split(None, 3)
        if len(fields) < 4:
            continue
        key = fields[0].split('.')[0]
        if key not in BODIES:
            continue
        names = re.sub(r'\s*\(.*?\)', '', fields[3])
        for one in [x.strip() for x in names.split('/')]:
            if not one:
                continue
            if not one.lower().startswith('canon'):
                one = 'Canon EOS ' + one
            out.append((one, key))
    seen, table = set(), []
    for name, key in out:
        if name.lower() in seen:
            continue
        seen.add(name.lower())
        table.append((name, key))
    return table


def matrix_text(key, vals):
    rows = []
    for r in range(3):
        cells = ', '.join('%.4ff' % (v / 10000.0) for v in vals[3 * r:3 * r + 3])
        rows.append('    { %s }' % cells)
    body = ',\n'.join(rows)
    return 'static const float XYZ_%s[3][3] = {\n%s };\n' % (key, body)


def main():
    ap = argparse.ArgumentParser(description="The bodies M-Film knows, as a header the darkroom includes.")
    ap.add_argument("out")
    ap.add_argument("--cameras", default=str(HERE.parent.parent / "cameras.txt"))
    a = ap.parse_args()

    out = [BANNER]
    for key, vals in MATRICES.items():
        out.append(matrix_text(key, vals))
    out.append('/* the body the fork is built for: its scale, and the colours above it takes.\n'
               ' * A frame whose body is not one of these is left on the last arm. */\n')
    arms = [k for k in BODIES if k != FALLBACK]
    for i, key in enumerate(arms):
        white, matrix = BODIES[key]
        out.append('%s defined(CONFIG_%s)\n#define WHITE_LEVEL %d\n#define XYZ_CAM XYZ_%s\n'
                   % ('#if' if i == 0 else '#elif', key, white, matrix))
    white, matrix = BODIES[FALLBACK]
    out.append('#else   /* the EOS M, and the bodies that share its sensor */\n'
               '#define WHITE_LEVEL %d\n#define XYZ_CAM XYZ_%s\n#endif\n\n' % (white, matrix))

    out.append('/* the bodies a frame may name, and what each takes it to; the names are\n'
               ' * Canon\'s own, from ml-dev/cameras.txt */\n')
    out.append('static const struct { const char *name; int white; const float (*xyz)[3]; } BODIES[] =\n{\n')
    names = names_from(a.cameras)
    for name, key in names:
        white, matrix = BODIES[key]
        pad = ' ' * max(1, 30 - len(name))
        out.append('    { "%s",%s%d, XYZ_%s },\n' % (name, pad, white, matrix))
    out.append('};\n\n#endif\n')

    Path(a.out).write_text(''.join(out))
    print('gencams: %s, %d names over %d bodies' % (a.out, len(names), len(BODIES)))


if __name__ == "__main__":
    main()
